"""report.py -- the robustness sweep's report (Addendum 5; not pre-registered).

The sweep builds the next 20 eligible repositories per stack after the replay sample once,
at their cutoff commit, and audits them once (bench/replay/replay.py at commits 0). This
turns that output into sweep.csv (one row per repository) and sweep.md:

  python bench/sweep/report.py --builds builds-*.csv --audits DIR

DIR holds out/<owner__name>/<sha>/ with each audit's findings.json, crawl.json and
audit.log. It flags, for a person to look at, never as a verdict:

- crash: sitemend could not audit a site that built (the next #51);
- slow: an audit that took over SLOW seconds;
- site-wide: a high or critical measured rule that fires on at least SITEWIDE of a site's
  pages (and at least MIN_PAGES pages), a pattern that is usually a misfire, not a site
  where nearly every page is genuinely broken.
"""
import argparse
import csv
import json
import os
from collections import Counter

SLOW = 600
SITEWIDE = 0.9
MIN_PAGES = 10
FIELDS = ["repo", "status", "build_seconds", "audit_seconds", "pages", "critical", "high",
          "medium", "low", "flags", "error"]


def flags_for(findings, pages, audit_seconds):
    out = []
    if audit_seconds and float(audit_seconds) > SLOW:
        out.append("slow ({0:.0f} s)".format(float(audit_seconds)))
    if pages >= MIN_PAGES:
        hit = Counter()
        for f in findings:
            if f["severity"] in ("critical", "high") and f.get("confidence", "high") == "high":
                hit[f["id"]] += len(set(f.get("pages") or []))
        for rule, n in sorted(hit.items()):
            if n >= SITEWIDE * pages:
                out.append("site-wide {0} ({1} of {2} pages)".format(rule, min(n, pages), pages))
    return out


def page_count(d):
    """Pages audited, from report-data.json (small, no page text), else crawl.json. An
    antivirus can quarantine a crawl.json whose site text looks like attack payloads
    (a SQL-injection knowledge base did); both files carry the same meta.page_count."""
    for name in ("report-data.json", "crawl.json"):
        path = os.path.join(d, name)
        if os.path.exists(path):
            with open(path, encoding="utf-8") as fh:
                return json.load(fh)["meta"]["page_count"]
    raise FileNotFoundError("no report-data.json or crawl.json in " + d)


def summarize(builds, audits):
    rows = []
    for b in builds:
        row = {k: b.get(k, "") for k in ("repo", "status", "build_seconds", "audit_seconds", "error")}
        d = os.path.join(audits, "out", b["repo"].replace("/", "__"), b["sha"])
        findings, pages = [], 0
        if b["status"] == "ok":
            with open(os.path.join(d, "findings.json"), encoding="utf-8") as fh:
                findings = json.load(fh)["findings"]
            pages = page_count(d)
        sev = Counter(f["severity"] for f in findings)
        if b["status"] == "audit_failed":
            # A build with no HTML pages is not a sitemend failure (Addendum 7).
            fl = ["no pages" if "crawled 0 pages" in (b.get("error") or "") else "crash"]
        else:
            fl = []
        fl += flags_for(findings, pages, b.get("audit_seconds"))
        row.update(pages=pages, flags="; ".join(fl), **{s: sev[s] for s in ("critical", "high", "medium", "low")})
        rows.append(row)
    return rows


def markdown(rows, sources):
    built = [r for r in rows if r["status"] in ("ok", "audit_failed")]
    crashes = [r for r in rows if r["status"] == "audit_failed" and r["flags"].startswith("crash")]
    empty = [r for r in rows if r["flags"].startswith("no pages")]
    out = ["# Robustness sweep", "",
           "Not pre-registered (Addendum 5). Generated by `bench/sweep/report.py` from {0}. Each "
           "repository was built once at its last commit before the cutoff and audited once with the "
           "frozen sitemend.".format(", ".join("`{0}`".format(s) for s in sources)), "",
           "**{0} repositories: {1} built, {2} did not; of those built, {3} had no HTML pages and "
           "sitemend could not audit {4}.**".format(
               len(rows), len(built), len(rows) - len(built), len(empty), len(crashes)), ""]
    flagged = [r for r in rows if r["flags"]]
    out += ["## Flagged for review ({0})".format(len(flagged)), ""]
    if flagged:
        out += ["| Repository | Flags | Error |", "|---|---|---|"] + [
            "| {0} | {1} | {2} |".format(r["repo"], r["flags"], (r["error"] or "").replace("|", "\\|")[:160])
            for r in flagged]
    else:
        out.append("Nothing flagged.")
    out += ["", "## Every repository", "",
            "| Repository | Status | Pages | Critical | High | Medium | Low | Audit s |",
            "|---|---|---|---|---|---|---|---|"] + [
        "| {repo} | {status} | {pages} | {critical} | {high} | {medium} | {low} | {audit_seconds} |".format(**r)
        for r in rows]
    out += ["", "Flags are leads for a person to check, not verdicts. A crash or a confirmed misfire "
                "is logged as an issue; while the measured version is frozen it is not fixed."]
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--builds", nargs="+", required=True)
    ap.add_argument("--audits", required=True, help="folder that holds out/")
    ap.add_argument("--out", default=os.path.dirname(os.path.abspath(__file__)))
    args = ap.parse_args(argv)
    builds = []
    for p in args.builds:
        with open(p, encoding="utf-8", newline="") as fh:
            builds += list(csv.DictReader(fh))
    rows = summarize(builds, args.audits)
    with open(os.path.join(args.out, "sweep.csv"), "w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=FIELDS, lineterminator="\n")
        w.writeheader()
        w.writerows(rows)
    with open(os.path.join(args.out, "sweep.md"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(markdown(rows, [os.path.basename(p) for p in args.builds]))
    print("wrote sweep.csv and sweep.md in", args.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
